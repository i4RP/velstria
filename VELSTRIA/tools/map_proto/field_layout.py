#!/usr/bin/env python3
"""Generate default map from the October 19 field survey (uv: numpy, Pillow)."""
import base64, json, math
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[2]; HERE=Path(__file__).resolve().parent
data=json.loads((HERE/'field_annotations.json').read_text())
poses=json.loads((HERE/'field_camera.json').read_text())['frames']; cam=data['camera']
p=math.radians(cam['pitch']);f=315/math.tan(math.radians(cam['verticalFOV'])/2);d=cam['distance']
def world(view, pixel):
    x,y=poses['IMG_'+view]['hero'];y+=cam['lead'];u,v=pixel
    dy=(315-v)*d/(f*math.sin(p)-(315-v)*math.cos(p))
    return [x+(u-684)*(d+dy*math.cos(p))/f,y+dy]
def vec(pt): return 'Vec2(%.3f, %.3f)'%(pt[0]*100,pt[1]*100)
def polygon(points): return '['+', '.join(map(vec,points))+']'
def mini(pt):
    t=data['minimapTransform'];return [(pt[0]-t['originX'])*t['metersPerPixel'],(t['originY']-pt[1])*t['metersPerPixel']]
walls=[[world(o['view'],q) for q in o['points']] for o in data['walls']]
bushes=[[world(o['view'],q) for q in o['points']] for o in data['bushes']]
im=Image.new('L',(600,600));draw=ImageDraw.Draw(im)
for i,outline in enumerate(bushes):draw.polygon([(x/.162,y/.162) for x,y in outline],fill=i+1)
cells=np.array(im);n=len(bushes);mirrored=cells[::-1,::-1].copy();mirrored[mirrored>0]+=n
cells=np.maximum(cells,mirrored).ravel().tolist()
encoded=bytearray();i=0
while i<len(cells):
    value=cells[i];j=i+1
    while j<len(cells) and cells[j]==value:j+=1
    run=j-i;encoded.append(value)
    while run>=128:encoded.append((run&127)|128);run>>=7
    encoded.append(run);i=j
rle=base64.b64encode(encoded).decode()
bank=[[3,86],[10,81],[17,73],[22,65],[27,59],[34,55],[42,48],[49,43],[54,36],[59,30],[65,25],[73,20],[81,11],[86,3]]
river=bank+[[97.2-x,97.2-y] for x,y in bank]
campRows=[]
for kind,values in data['campPixels'].items():
    view,point=values[0];campRows.append('        (.'+kind+', '+vec(world(view,point))+')')
s='''// Generated by tools/map_proto/field_layout.py from the 2026-10-19 field survey.
// Coordinates: centimetres. Opposite terrain is a half turn, including boss walls.
import Foundation

public enum StageReferenceLayout {
    public static let pitchDegrees: Float = '''+str(cam['pitch'])+'''
    public static let verticalFOV: Float = '''+str(cam['verticalFOV'])+'''
    public static let cameraDistance: Float = '''+str(cam['distance'])+'''
    public static let cameraLead: Float = '''+str(cam['lead'])+'''
    public static let walls: [[Vec2]] = [
'''+',\n'.join('        '+polygon(v) for v in walls)+'''
    ]
    public static let wallKinds: [String] = ['''+', '.join('"'+o['kind']+'"' for o in data['walls'])+''']
    public static let bushNames = ['''+', '.join('"'+o['id']+'"' for o in data['bushes'])+''']
    public static let bushOutlines: [[Vec2]] = [
'''+',\n'.join('        '+polygon(v) for v in bushes)+'''
    ]
    public static let lowStones: [[Vec2]] = []
    public static let riverMark = Vec2(4860, 4860)
    public static let walkableSamples: [Vec2] = [Vec2(4860, 4860), Vec2(4400, 3800)]
    static let river = '''+polygon(river)+'''
    static let northBoss = '''+vec(data['bossCenter'])+'''
    static let blueCamps: [(CampKind, Vec2)] = [
'''+',\n'.join(campRows)+'''
    ]
    static let blueTowers: [(Lane, Int, Vec2)] = [
'''+',\n'.join('        (.'+lane+', '+str(tier)+', '+vec(mini(pt))+')' for lane,tier,pt in data['blueTowers'])+'''
    ]
    public struct View: Sendable {
        public let name: String
        public let hero: Vec2
        public var focus: Vec2 { hero + Vec2(0, Double(StageReferenceLayout.cameraLead) * 100) }
    }
    public static let views: [View] = [
'''+',\n'.join('        View(name: "'+name+'", hero: '+vec(v['hero'])+')' for name,v in poses.items())+'''
    ]
    static let mask = BushMask(cell: 16.2, cols: 600, rows: 600, runLengthBase64: """
'''+ '\n'.join('        '+rle[i:i+120] for i in range(0,len(rle),120))+'''
        """)!
}

extension MapDefinition {
    mutating func applyReferenceLayout() {
        let edge = size
        let mirror: (Vec2) -> Vec2 = { Vec2(edge - $0.x, edge - $0.y) }
        let outlines = StageReferenceLayout.walls + StageReferenceLayout.walls.map { $0.map(mirror) }
        obstacles = outlines.map { Obstacle.smoothPolygon($0, tolerance: 0.1, maxSegment: 50) }
        river = Obstacle.smoothPolygon(StageReferenceLayout.river, tolerance: 2, maxSegment: 120)
        for (lane, tier, point) in StageReferenceLayout.blueTowers {
            let opposite: Lane = lane == .top ? .bot : (lane == .bot ? .top : .mid)
            for i in towers.indices where !towers[i].isCore && towers[i].tier.rawValue == tier {
                if towers[i].team == .blue && towers[i].lane == lane { towers[i].pos = point }
                if towers[i].team == .red && towers[i].lane == opposite { towers[i].pos = mirror(point) }
            }
        }
        for (kind, point) in StageReferenceLayout.blueCamps {
            for i in camps.indices where camps[i].kind == kind {
                camps[i].pos = camps[i].side == .blue ? point : mirror(point)
            }
        }
        for i in camps.indices {
            if camps[i].kind == .ancientColossus { camps[i].pos = StageReferenceLayout.northBoss }
            if camps[i].kind == .astralWyrm { camps[i].pos = mirror(StageReferenceLayout.northBoss) }
            if camps[i].kind == .mossWanderer { camps[i].pos = Vec2(4200, 5520) }
            if camps[i].kind == .treasureCrab {
                let point = Vec2(1760, 6840)
                camps[i].pos = camps[i].pos.y > edge / 2 ? point : mirror(point)
            }
        }
        for camp in camps where camp.kind.isBoss {
            obstacles.append(.polygon(BossPitGeometry.wall(center: camp.pos, lower: camp.pos.y < edge / 2)))
        }
        let mask = StageReferenceLayout.mask.carved(by: obstacles)
        bushMask = mask
        brushes = MapDefinition.brushAreas(of: mask)
    }
}
'''
(ROOT/'Packages/VelstriaCore/Sources/VelstriaCore/Sim/StageReferenceLayout.swift').write_text(s)
print('Generated',len(walls)*2+2,'walls,',len(bushes)*2,'bushes,',len(poses),'capture poses')
