#!/usr/bin/env python3
"""Generate shared collision/visibility footprints from manually traced reference pixels.
Uses Pillow only for polygon rasterization. No colour classification is performed.
"""
import json, math, base64
from pathlib import Path
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[2]
data=json.loads(Path(__file__).with_suffix('.json').read_text())
x,y,d,p,fov=data['camera']; p=math.radians(p); f=296/math.tan(math.radians(fov)/2)
def world(pt):
 u,v=pt; t=(296-v)/f; dy=t*d/(math.sin(p)-t*math.cos(p)); return [(x+(u-540)*(d+dy*math.cos(p))/f)*100,(y+dy)*100]
def vec(pt):return 'Vec2(%.3f, %.3f)'%tuple(world(pt))
def polygons(key):return ',\n'.join('        ['+', '.join(map(vec,ps))+']' for ps in data[key])
im=Image.new('L',(600,600));draw=ImageDraw.Draw(im)
for i,ps in enumerate(data['bushes']):draw.polygon([(a/16.2,b/16.2) for a,b in map(world,ps)],fill=i+1)
a=list(im.getdata());n=len(data['bushes'])
# The traced upper-right half is authoritative; retain only that half, then rotate.
for r in range(600):
 for c in range(600):
  if r+c<599:a[r*600+c]=0
for i in range(len(a)//1):
 if a[i]:a[len(a)-1-i]=a[i]+n if a[i]<=n else a[len(a)-1-i]
b=bytearray();i=0
while i<len(a):
 v=a[i];j=i+1
 while j<len(a) and a[j]==v:j+=1
 count=j-i;b.append(v)
 while count>=128:b.append((count&127)|128);count>>=7
 b.append(count);i=j
encoded=base64.b64encode(b).decode()
s='''// Generated by tools/map_proto/reference_layout.py. Coordinates are relayout centimetres.
import Foundation

public enum StageReferenceLayout {
    public static let walls: [[Vec2]] = [
'''+polygons('walls')+'''
    ]
    public static let riverMark = '''+vec([400,430])+'''
    public static let walkableSamples: [Vec2] = ['''+', '.join(map(vec,data['walkable']))+''']
    public static let lowStones: [[Vec2]] = [
'''+polygons('lowStones')+'''
    ]
    static let towers: [(Lane, Int, Vec2)] = [
'''+',\n'.join('        (.'+lane+', '+str(tier)+', '+vec(pt)+')' for lane,tier,pt in data['redTowers'])+'''
    ]
    static let redCamps: [Vec2] = ['''+', '.join(map(vec,data['redCamps']))+''']
    static let mask = BushMask(cell: 16.2, cols: 600, rows: 600, runLengthBase64: """
'''+ '\n'.join('        '+encoded[i:i+120] for i in range(0,len(encoded),120))+'''
        """)!

    /// Boss placement and the surrounding 9 m remain under the sanctuary workstream.
    static func protected(_ point: Vec2, map: MapDefinition) -> Bool {
        map.camps.contains { $0.kind.isBoss && $0.pos.distance(to: point) < 900 }
    }
}

extension MapDefinition {
    mutating func applyReferenceLayout() {
        let old = self
        let mirror: (Vec2) -> Vec2 = { Vec2(old.size - $0.x, old.size - $0.y) }
        let outlines = StageReferenceLayout.walls + StageReferenceLayout.walls.map { $0.map(mirror) }
        obstacles = outlines.filter { points in
            !StageReferenceLayout.protected(points.reduce(.zero, +) / Double(points.count), map: old)
        }.map { Obstacle.smoothPolygon($0, tolerance: 0.1, maxSegment: 50) }
        obstacles += old.obstacles.filter { StageReferenceLayout.protected($0.bounds.center, map: old) }
        for (lane, tier, point) in StageReferenceLayout.towers {
            let opposite: Lane = lane == .top ? .bot : (lane == .bot ? .top : .mid)
            for i in towers.indices where !towers[i].isCore && towers[i].tier.rawValue == tier {
                if towers[i].team == .red && towers[i].lane == lane { towers[i].pos = point }
                if towers[i].team == .blue && towers[i].lane == opposite { towers[i].pos = mirror(point) }
            }
        }
        // Non-boss camp pairs follow the same half-turn as their surrounding walls.
        for i in 0..<5 {
            camps[i + 5].pos = StageReferenceLayout.redCamps[i]
            camps[i].pos = mirror(StageReferenceLayout.redCamps[i])
        }
        var cells = StageReferenceLayout.mask.cells
        if let previous = old.bushMask {
            let offset = Int(cells.max() ?? 0)
            for r in 0..<600 { for c in 0..<600 {
                let point = StageReferenceLayout.mask.center(col: c, row: r)
                if StageReferenceLayout.protected(point, map: old) {
                    cells[r * 600 + c] = previous.bush(at: point).map { UInt8($0 + offset + 1) } ?? 0
                }
            } }
        }
        // Reindex surviving regions so visibility and rendering use the same dense IDs.
        let ids = Array(Set(cells.filter { $0 != 0 })).sorted()
        var remap = [UInt8](repeating: 0, count: 256)
        for (i, id) in ids.enumerated() { remap[Int(id)] = UInt8(i + 1) }
        let mask = BushMask(cell: 16.2, cols: 600, rows: 600, cells: cells.map { remap[Int($0)] }).carved(by: obstacles)
        bushMask = mask
        brushes = MapDefinition.brushAreas(of: mask)
    }
}
'''
(root/'Packages/VelstriaCore/Sources/VelstriaCore/Sim/StageReferenceLayout.swift').write_text(s)
print('Generated StageReferenceLayout.swift')
